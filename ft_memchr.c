#include "libft.h"

void	*ft_memchr(const void *s, int c, size_t n)
{
	const unsigned char	*bytes;
	size_t				i;

	bytes = s;
	i = 0;
	while (i < n)
	{
		if (bytes[i] == (unsigned char)c)
			return ((void *)(bytes + i));
		i++;
	}
	return (NULL);
}
